function renderSkillMarkdown(skill: StarterSkill): string {
  return [
    "---",
    `name: ${skill.name}`,
    `description: ${skill.description}`,
    "triggers:",
    ...skill.triggers.map((trigger) => `  - ${trigger}`),
    "---",
    skill.body.trim(),
    "",
  ].join("\n");
}

export async function ensureStarterSkillsInstalled(options: { skillsDir: string }): Promise<{
  installed: number;
  skipped: number;
  skillsDir: string;
}> {
  const skillsDir = options.skillsDir;
  await mkdir(skillsDir, { recursive: true });

  let installed = 0;
  let skipped = 0;

  for (const skill of STARTER_SKILLS) {
    const skillDir = join(skillsDir, skill.id);
    const skillPath = join(skillDir, "SKILL.md");
    if (existsSync(skillPath)) {
      skipped++;
      continue;
    }
    await mkdir(skillDir, { recursive: true });
    await writeFile(skillPath, renderSkillMarkdown(skill), "utf-8");
    installed++;
  }

  if (installed > 0) {
    logger.info("[StarterSkills] Installed starter skills", { installed, skipped, skillsDir });
  }

  return { installed, skipped, skillsDir };
}
